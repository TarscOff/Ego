// The project pin `.harness/harness.md` (decision Q94): generated, current pin canonical, provenance-stamped.
import { join } from 'node:path';
import { parseMarkdown } from '../util/markdown.ts';
import { stringifyYaml, type YamlValue } from '../util/yaml.ts';
import { readTextIfExists, writeAtomic, isFile } from '../util/fs.ts';
import { sha256Canonical } from '../util/hash.ts';
import { isDevelopmentVersion } from './identity.ts';

export interface PinRelease {
  tarballSha256: string;
  keyId: string;
}

export interface Pin {
  name: string;
  version: string;
  integrity: string;
  release?: PinRelease;
  sources: string[];
  schemas: Record<string, string>;
  node: string;
  profile: string;
  taskSource?: string;
  /** sha256 over the canonical ego block; hand edits are detected by recomputation */
  stamp: string;
}

export const PIN_RELATIVE_PATH = join('.harness', 'harness.md');

export class PinError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'PinError';
  }
}

export function pinPath(projectRoot: string): string {
  return join(projectRoot, PIN_RELATIVE_PATH);
}

export function hasPin(projectRoot: string): boolean {
  return isFile(pinPath(projectRoot));
}

function stampOf(p: Omit<Pin, 'stamp'>): string {
  return sha256Canonical({
    name: p.name,
    version: p.version,
    integrity: p.integrity,
    release: p.release ?? null,
    sources: p.sources,
    schemas: p.schemas,
    node: p.node,
    profile: p.profile,
    taskSource: p.taskSource ?? null,
  });
}

export function readPin(projectRoot: string): Pin {
  const path = pinPath(projectRoot);
  const text = readTextIfExists(path);
  if (text === null) throw new PinError(`not initialized: ${path} is missing; run \`ego init\``);
  const doc = parseMarkdown(path, text);
  const ego = doc.frontmatter['ego'];
  if (ego === null || typeof ego !== 'object' || Array.isArray(ego))
    throw new PinError(`${path}: frontmatter "ego" block is missing`);
  const e = ego as Record<string, YamlValue>;
  const str = (k: string): string => {
    const v = e[k];
    if (typeof v !== 'string' || v === '') throw new PinError(`${path}: ego.${k} must be a non-empty string`);
    return v;
  };
  const sources = Array.isArray(e['sources'])
    ? (e['sources'] as YamlValue[]).filter((s): s is string => typeof s === 'string')
    : [];
  const schemasRaw = e['schemas'];
  const schemas: Record<string, string> = {};
  if (schemasRaw && typeof schemasRaw === 'object' && !Array.isArray(schemasRaw)) {
    for (const [k, v] of Object.entries(schemasRaw as Record<string, YamlValue>))
      if (typeof v === 'string') schemas[k] = v;
  }
  const releaseRaw = e['release'];
  let release: PinRelease | undefined;
  if (releaseRaw && typeof releaseRaw === 'object' && !Array.isArray(releaseRaw)) {
    const r = releaseRaw as Record<string, YamlValue>;
    if (typeof r['tarballSha256'] === 'string' && typeof r['keyId'] === 'string')
      release = { tarballSha256: r['tarballSha256'], keyId: r['keyId'] };
  }
  const base: Omit<Pin, 'stamp'> = {
    name: str('name'),
    version: str('version'),
    integrity: str('integrity'),
    sources,
    schemas,
    node: typeof e['node'] === 'string' ? e['node'] : '>=24',
    profile: typeof e['profile'] === 'string' ? e['profile'] : 'STRICT',
  };
  if (release) base.release = release;
  if (typeof e['taskSource'] === 'string') base.taskSource = e['taskSource'];
  const stamp = typeof e['stamp'] === 'string' ? e['stamp'] : '';
  const expected = stampOf(base);
  if (stamp !== expected)
    throw new PinError(
      `${path}: provenance stamp mismatch; the pin was edited by hand. Regenerate it with \`ego init\`, \`ego upgrade\` or \`ego sources\`.`,
    );
  return { ...base, stamp };
}

export function writePin(projectRoot: string, pin: Omit<Pin, 'stamp'>): Pin {
  const stamp = stampOf(pin);
  const ego: Record<string, YamlValue> = {
    name: pin.name,
    version: pin.version,
    integrity: pin.integrity,
    sources: pin.sources,
    schemas: pin.schemas,
    node: pin.node,
    profile: pin.profile,
    stamp,
  };
  if (pin.release) ego['release'] = { tarballSha256: pin.release.tarballSha256, keyId: pin.release.keyId };
  if (pin.taskSource) ego['taskSource'] = pin.taskSource;
  const body = `---
generated: true
generator: harness
schema: ego.pin/1
ego:
${stringifyYaml(ego, 2)}
---
# EGO project pin

This file is generated by \`ego init\`, \`ego upgrade\`, \`ego rollback\` and \`ego sources\`; do not edit it by
hand (the provenance stamp detects edits). It pins the exact EGO runtime that governs this repository:

- **Runtime identity**: \`${pin.version}\` with content hash \`${pin.integrity.slice(0, 16)}…\`. Every developer and every host
  running EGO here executes this identity, or stops until \`ego sync\` obtains it.
- **Sources**: where \`ego sync\` may obtain the runtime and its signed release metadata, in order.
- **Profile**: \`${pin.profile}\` (the compiled overlay is authoritative once the runtime runs; the stricter of the two governs).

Trust state (registry, local tarball, signed release) is machine-local and lives under \`EGO_HOME\`, never here.
${isDevelopmentVersion(pin.version) ? '\n> This pin references a **development identity**. Development identities are permitted only under the STANDARD profile and can never reach signed-release trust.\n' : ''}`;
  writeAtomic(pinPath(projectRoot), body);
  return { ...pin, stamp };
}
