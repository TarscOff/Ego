test('index-first dispatch: IDENTITY_CONFLICT, TAMPERED and REVOKED states refuse with a remedy; ego.node is enforced', async () => {
  const dir = repo();
  const home = mkdtempSync(join(tmpdir(), 'ego-home-'));
  const env = cleanEnv(home);
  await run(['init'], dir, env);
  const { readPin: rp } = await import('../../packages/kernel/src/launcher/pin.ts');
  const pin = rp(dir);
  const { indexPath, setIdentityState, egoHome } = await import('../../packages/kernel/src/launcher/home.ts');
  const h = egoHome(env);
  const idxFile = indexPath(h, pin.name, pin.version);
  const original = readFileSync(idxFile, 'utf8');
  const entry = JSON.parse(original) as { identity: string };
  entry.identity = 'b'.repeat(64);
  writeFileSync(idxFile, JSON.stringify(entry));
  const conflict = await run(['status'], dir, env);
  assert.equal(conflict.code, 2);
  assert.match(conflict.err, /IDENTITY_CONFLICT/);
  writeFileSync(idxFile, original);
  // a different package name claiming the same version string with another identity is a conflict too
  const other = JSON.parse(original) as { name: string; identity: string };
  other.name = '@other/ego';
  other.identity = 'c'.repeat(64);
  writeFileSync(indexPath(h, '@other/ego', pin.version), JSON.stringify(other));
  const cross = await run(['status'], dir, env);
  assert.equal(cross.code, 2);
  assert.match(cross.err, /one version string maps to exactly one runtime identity/);
  rmSync(indexPath(h, '@other/ego', pin.version));
  for (const state of ['TAMPERED', 'REVOKED'] as const) {
    setIdentityState(h, pin.name, pin.version, state);
    const r = await run(['status'], dir, env);
    assert.equal(r.code, 2);
    assert.match(r.err, new RegExp(`is ${state}; remedy`));
  }
  setIdentityState(h, pin.name, pin.version, undefined);
  assert.equal((await run(['status'], dir, env)).code, 0);
  const { writePin: wp } = await import('../../packages/kernel/src/launcher/pin.ts');
  const { stamp: _s, ...base } = pin;
  wp(dir, { ...base, node: '>=99' });
  const node = await run(['status'], dir, env);
  assert.equal(node.code, 2);
  assert.match(node.err, /pins node >=99/);
});

