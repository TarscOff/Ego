function cleanEnv(home: string): NodeJS.ProcessEnv {
  const env: NodeJS.ProcessEnv = {
    PATH: process.env['PATH'],
    HOME: process.env['HOME'],
    EGO_HOME: home,
    LANG: 'C',
  };
  return env;
}

/** the environment Claude Code gives a hook process: the project-dir marker distinguishes it from an agent shell (K14) */
function hostEnv(env: NodeJS.ProcessEnv, dir: string): NodeJS.ProcessEnv {
  return { ...env, CLAUDE_PROJECT_DIR: dir };
}

function repo(): string {
  const dir = mkdtempSync(join(tmpdir(), 'ego-cli-'));
  spawnSync('git', ['init', '-q'], { cwd: dir });
  spawnSync('git', ['config', 'user.email', 't@example.com'], { cwd: dir });
  spawnSync('git', ['config', 'user.name', 't'], { cwd: dir });
  spawnSync('git', ['remote', 'add', 'origin', 'git@github.com:acme/demo.git'], { cwd: dir });
  writeFileSync(
    join(dir, 'package.json'),
    JSON.stringify({
      name: 'demo',
      version: '1.0.0',
      scripts: { deploy: 'git push origin main', build: 'tsc' },
      devDependencies: { typescript: '^5', react: '^19' },
    }),
  );
  writeFileSync(join(dir, 'AGENTS.md'), '# Demo rules\n\nAlways run the tests before committing.\n');
  mkdirSync(join(dir, '.git', 'hooks'), { recursive: true });
  writeFileSync(join(dir, '.git', 'hooks', 'pre-commit'), '#!/bin/sh\necho existing\n');
  spawnSync('git', ['add', '-A'], { cwd: dir });
  spawnSync('git', ['commit', '-qm', 'init'], { cwd: dir });
  return dir;
}

async function run(
  argv: string[],
  cwd: string,
  env: NodeJS.ProcessEnv,
  stdin = '',
): Promise<{ code: number; out: string; err: string }> {
  const out: string[] = [];
  const err: string[] = [];
  const code = await main(argv, {
    cwd,
    env,
    stdin,
    out: (s) => out.push(s),
    err: (s) => err.push(s),
    now: () => '2026-09-14T10:00:00.000Z',
  });
  return { code, out: out.join('\n'), err: err.join('\n') };
}

